/*
 * إعادة تحميل الصفحات المفتوحة من جوه السيرفس ووركر.
 *
 * ## المشكلة اللي ده بيحلّها وغيره مابيحلّهاش
 *
 * الحل السابق كان في صفحة الويب: بتسمع `controllerchange` وتحدّث نفسها.
 * وده شغّال — **بس للصفحات اللي بتشغّل الكود الجديد**. والمتصفح اللي
 * كاش نسخة قديمة بيفضل شغّال بكود مافيهوش السامع ده، فمفيش حاجة في
 * الصفحة نفسها هتحدّثها. يعني اللي واقع في المشكلة هو بالظبط اللي الحل
 * مابيوصلهوش، وبيفضل محتاج Refresh باليد كل مرة.
 *
 * والسيرفس ووركر بيقدر يعمل اللي الصفحة مش قادرة عليه: `client.navigate`
 * بيعيد تحميل الصفحة من برّه، من غير أي تعاون من الكود اللي شغّال جواها.
 * فأي متصفح — قديم أو جديد — بيتعالج من غير ما المستخدم يعمل حاجة.
 *
 * ## الحراسة من اللفّة
 *
 * `activate` بيحصل مرة واحدة لكل نسخة سيرفس ووركر، فالصفحات بتتحمّل مرة
 * لكل رفعة مش أكتر.
 *
 * وأول تركيب مستثنى: `self.registration.active` وقت التركيب بيقول لنا هل
 * كان فيه نسخة قبلنا ولا لأ. من غير الشرط ده، أول زيارة لأي حد كانت
 * بتتحمّل مرتين على الفاضي — الكود اللي شغّال ساعتها جه من الشبكة وهو
 * أحدث حاجة موجودة أصلًا.
 *
 * والملف ده بيتحقن في الـsw المولّد بـ`workbox.importScripts`، لأن
 * `generateSW` مابيسمحش بكود مننا جوه الملف نفسه.
 *
 * ## قيد مهم: العنوان ده بيتكاش للأبد
 *
 * `importScripts` جوه سيرفس ووركر بيتخزّن في كاش التسجيل **بالعنوان**،
 * ومابيتجابش تاني لما الـsw الرئيسي يتحدّث. يعني المتصفح اللي جاب
 * `/sw-reload.js` مرة هيفضل يشغّل نفس النسخة دي مهما رفعنا.
 *
 * فلو المنطق اللي هنا اتغيّر يومًا، **لازم العنوان يتغيّر معاه**
 * (`/sw-reload-2.js`) و`vite.config.ts` يشاور على الجديد. تعديل الملف
 * في مكانه مش هيوصل لحد فاتح النظام قبل كده.
 */

let updating = false;

self.addEventListener("install", () => {
  /* وجود نسخة نشطة وإحنا بنتركّب معناه إن دي رفعة مش أول تركيب */
  updating = Boolean(self.registration.active);
});

self.addEventListener("activate", (event) => {
  if (!updating) return;
  event.waitUntil(
    (async () => {
      /*
       * `includeUncontrolled` ضروري: إحنا لسه في `activate`، و`clientsClaim`
       * مانفّذش بعد — فالنسخة الجديدة لسه مش متحكّمة في أي صفحة.
       * ومن غير الشرط ده القائمة بترجع فاضية والصفحات مااتحدّثتش، وهو
       * بالظبط اللي الاختبار مسكه أول مرة.
       *
       * والصفحات اللي مش متحكوم فيها مالهاش لازمة تتحدّث نظريًا، بس
       * `updating` فوق أصلًا بيمنع أول تركيب — فاللي واصل لهنا رفعة على
       * صفحات كانت شغّالة على نسخة قبلها.
       */
      const open = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
      await Promise.all(
        open.map((client) => {
          try {
            /* `navigate` بيرجع null لو المتصفح رفض — مش حالة خطأ نوقف
             * عندها، الصفحة بتفضل شغّالة زي ما هي وبس */
            return client.navigate(client.url);
          } catch {
            return undefined;
          }
        }),
      );
    })(),
  );
});
