/**
 * تسجيل السيرفس ووركر.
 *
 * التسجيل من عندنا مش من السكربت اللي `vite-plugin-pwa` بيحقنه
 * (`injectRegister: null`)، عشان يكون عندنا مكان واحد نتحكّم منه.
 *
 * وإعادة التحميل بعد الرفعة **مش هنا** — هي في `public/sw-reload.js`
 * اللي بيتحقن جوه السيرفس ووركر نفسه.
 *
 * وده كان تصحيح لحل قبله كان في الصفحة: بيسمع `controllerchange` ويحدّث.
 * الحل ده بيشتغل بس على الصفحات اللي بتشغّل الكود الجديد، والمتصفح اللي
 * كاش نسخة قديمة بيفضل بكود مافيهوش السامع — يعني اللي واقع في المشكلة
 * هو نفسه اللي الحل مش بيوصله. الـsw بيقدر يعيد تحميل الصفحة من برّه،
 * فالمعالجة بتوصل للقديم والجديد.
 */
export function registerServiceWorker(): void {
  /* سيرفر التطوير مابيبنيش `sw.js`، فبيرد بـ`index.html` على أي مسار —
   * والمتصفح بيرفضه وبيسيب خطأ MIME في الكونسول. */
  if (!import.meta.env.PROD) return;
  if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return;

  window.addEventListener("load", () => {
    void navigator.serviceWorker.register("/sw.js", { scope: "/" }).catch(() => {
      /* الرفض مش حالة خطأ نوقف عندها: النظام بيشتغل من غير سيرفس ووركر،
       * بيفقد العمل أوفلاين بس. والمتصفح بيرفض التسجيل في حالات عادية
       * زي التصفح المتخفي. */
    });
  });
}
