/**
 * تسجيل السيرفس ووركر، والأهم: إعادة تحميل الصفحة لما نسخة جديدة تتولّى.
 *
 * المشكلة اللي بتحلّها:
 *
 * الـsw المولّد فيه `skipWaiting()` و`clientsClaim()`، يعني أول ما نسخة
 * جديدة تتركّب بتتولّى الصفحات المفتوحة على طول. بس الصفحة المفتوحة دي
 * **لسه شغّالة بالكود القديم** — وملفاته اتمسحت من الكاش لأن الـsw
 * الجديد بيعمل `cleanupOutdatedCaches()`. والنتيجة صفحة نصها قديم ونصها
 * جديد، ولازم المستخدم يعمل Refresh بإيده عشان تظبط. وده كان بيحصل مع
 * **كل رفعة** لكل واحد فاتح النظام.
 *
 * وكمان الـsw بيقدّم `index.html` من الكاش الأول (`NavigationRoute`)،
 * فاللي فاتح النظام بيفضل على النسخة القديمة لحد ما يحدّث.
 *
 * الحل: نسمع `controllerchange` ونحدّث مرة واحدة لوحدنا.
 *
 * وفرق مهم بين «أول تركيب» و«تحديث»: أول زيارة الصفحة مش متحكوم فيها،
 * والـsw بيتولّاها بعد ما تحمّل — والكود اللي شغّال ساعتها هو الأحدث
 * أصلًا لأنه جه من الشبكة. فلو حدّثنا هناك كمان، كل زيارة أولى بتتحمّل
 * مرتين على الفاضي.
 *
 * والفرق ده بيتقاس **وقت الحدث**، مش وقت تحميل الصفحة. لو قرينا الحالة
 * مرة واحدة في الأول، الصفحة اللي فتحت على جهاز جديد بتفضل طول عمرها
 * «أول تركيب» — فلو اترفعت نسخة جديدة وهي مفتوحة مش هتحدّث، وهي بالظبط
 * الحالة اللي بنحاول نحلّها.
 */
export function registerServiceWorker(): void {
  if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return;

  const sw = navigator.serviceWorker;
  let controlled = Boolean(sw.controller);
  let reloading = false;

  sw.addEventListener("controllerchange", () => {
    const wasControlled = controlled;
    controlled = Boolean(sw.controller);
    /* أول تركيب مش تحديث — مفيش كود قديم شغّال */
    if (!wasControlled || reloading) return;
    reloading = true;
    location.reload();
  });

  window.addEventListener("load", () => {
    void sw.register("/sw.js", { scope: "/" }).catch(() => {
      /* الرفض مش حالة خطأ نوقف عندها: النظام بيشتغل من غير سيرفس ووركر،
       * بيفقد العمل أوفلاين بس. والمتصفح بيرفض التسجيل في حالات عادية
       * زي التصفح المتخفي. */
    });
  });
}
