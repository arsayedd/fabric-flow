const START_B = 104;
const STOP = 106;

/** الحروف المدعومة في ترميز B: من المسافة للحرف `~` */
export function barcodeSafe(text: string): string {
  return [...text].filter((c) => c.charCodeAt(0) >= 32 && c.charCodeAt(0) <= 126).join("");
}

/**
 * بيرجّع أعراض الخطوط والفراغات بالتبادل، بتبدأ بخط.
 *
 * الوحدة مش مليمتر: هي **نسبة**. اللي بيرسم هو اللي بيقرر الوحدة قد
 * إيه، فنفس الشريط يطلع على ليبل ٣٠ مم وعلى ورقة A4.
 */
export function code128(text: string): number[] {
  const chars = barcodeSafe(text);
  const values = [...chars].map((c) => c.charCodeAt(0) - 32);
  // الشيك سم: البداية + كل قيمة مضروبة في مكانها، والباقي على ١٠٣
  const check = values.reduce((sum, v, i) => sum + v * (i + 1), START_B) % 103;
  const all = [START_B, ...values, check, STOP];
  return all.flatMap((v) => [...PATTERNS[v]].map(Number));
}

export type Bar = { x: number; w: number };

/** الخطوط السودا بس، بمواقعها — الفراغات مابتترسمش */
export function code128Bars(text: string): { bars: Bar[]; units: number } {
  const widths = code128(text);
  const bars: Bar[] = [];
  let x = 0;
  widths.forEach((w, i) => {
    if (i % 2 === 0) bars.push({ x, w });
    x += w;
  });
  return { bars, units: x };
}
